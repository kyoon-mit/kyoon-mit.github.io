"""5x7 proportional pixel font with descenders (cell height 9)."""
G = {}
def g(ch, *rows):
    rows = list(rows) + ["." * len(rows[0])] * (9 - len(rows))
    assert len(rows) == 9, ch
    w = len(rows[0])
    for r in rows:
        assert len(r) == w, (ch, rows)
    G[ch] = rows

